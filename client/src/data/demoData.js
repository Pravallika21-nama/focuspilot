function addDays(days) {
  const date = new Date(today);
  date.setDate(date.getDate() + days);
  return date.toISOString();
}

function session(subject, topic, offset, startTime, endTime, type, completed) {
  return {
    _id: `${subject}-${offset}-${startTime}`,
    subject,
    topic,
    date: addDays(offset),
    startTime,
    endTime,
    type,
    priority: subject === "Mathematics" || subject === "Physics" ? "high" : "medium",
    completed,
    notes: "Generated by AI priority balancing."
  };
}
